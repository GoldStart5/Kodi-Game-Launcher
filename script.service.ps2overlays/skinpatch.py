# -*- coding: utf-8 -*-
"""Draws the PS2 overlays inside a skin, behind its widgets.

Kodi always draws controls created by a script above the skin's own controls,
so to sit *behind* the skin the overlays have to live in the skin's XML. This
module turns the overlays into one skin include (Includes_PS2Overlays.xml) and
hooks it into the skin's own background include with two small marked edits:

  * Includes.xml          <include file="Includes_PS2Overlays.xml"/>
  * Includes_Global.xml   <include>PS2OverlaysBackground</include>
                          (last item of the skin's GlobalBackground include, so
                           it is above the skin's fanart and below everything
                           else, in every window that uses GlobalBackground)

The original files are backed up (<name>.ps2overlays.bak) before the first edit
and remove() strips the marked lines again, restoring them byte for byte.
"""
import os
import re
from xml.sax.saxutils import escape, quoteattr

import xbmc
import xbmcaddon

MARK_B = '<!-- PS2OVERLAYS BEGIN -->'
MARK_E = '<!-- PS2OVERLAYS END -->'
INCLUDE_FILE = 'Includes_PS2Overlays.xml'
INCLUDE_NAME = 'PS2OverlaysBackground'
BAK = '.ps2overlays.bak'
FOCUS_PROP = 'ps2overlays.focused'     # '0' = Kodi is not the foreground app
_STRIP = re.compile(r'[ \t]*' + re.escape(MARK_B) + r'.*?' + re.escape(MARK_E) + r'(\r?\n)?', re.S)

# skin id -> where its background include lives
SUPPORTED = {
    'skin.arctic.zephyr.martian': {
        'includes': 'Includes.xml',
        'host_file': 'Includes_Global.xml',
        'host_include': 'GlobalBackground',
    },
}


def log(msg):
    xbmc.log('[script.service.ps2overlays] skinpatch: %s' % msg, xbmc.LOGINFO)


def _read(path):
    with open(path, 'rb') as f:
        return f.read().decode('utf-8')


def _write(path, text):
    tmp = path + '.ps2tmp'
    with open(tmp, 'wb') as f:
        f.write(text.encode('utf-8'))
    os.replace(tmp, path)


def _nl(text):
    return '\r\n' if '\r\n' in text else '\n'


# ----------------------------------------------------------------------
def render_include(specs, media_base, note='', focus_fade=None):
    """specs: list of dicts (image, x, y, w, h, colour 'AARRGGBB', anims
    [(type, 'k=v k=v')], cond or None) -> text of the include file.
    focus_fade=(fade_in_ms, fade_out_ms) hides the whole group, with a fade,
    while the Home window property ps2overlays.focused is '0'."""
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!-- Generated by script.service.ps2overlays. Do not edit: it is rewritten '
           'when the addon settings change. %s -->' % escape(note),
           '<includes>',
           '    <include name="%s">' % INCLUDE_NAME,
           '        <control type="group">']
    if focus_fade is not None:
        fin, fout = focus_fade
        out.append('            <visible>!String.IsEqual(Window(Home).Property(%s),0)</visible>' % FOCUS_PROP)
        if fin > 0:
            out.append('            <animation effect="fade" start="0" end="100" time="%d" '
                       'tween="sine" easing="inout">Visible</animation>' % fin)
        if fout > 0:
            out.append('            <animation effect="fade" start="100" end="0" time="%d" '
                       'tween="sine" easing="inout">Hidden</animation>' % fout)
    def anim_lines(anims, pad):
        for kind, text in anims:
            attrs = ''
            for tok in text.split():
                k, _, v = tok.partition('=')
                attrs += ' %s=%s' % (k, quoteattr(v))
            out.append('%s<animation%s>%s</animation>' % (pad, attrs, kind))

    cur = None                       # specs sharing 'group' move together as one rigid unit
    for s in specs:
        g = s.get('group')
        if g != cur:
            if cur is not None:
                out.append('            </control>')
            if g is not None:
                out.append('            <control type="group">')
                anim_lines(s.get('group_anims', []), '                ')
            cur = g
        pad = '    ' if g is not None else ''
        out.append(pad + '            <control type="image">')
        out.append(pad + '                <left>%d</left><top>%d</top><width>%d</width><height>%d</height>'
                   % (round(s['x']), round(s['y']), max(1, round(s['w'])), max(1, round(s['h']))))
        out.append(pad + '                <aspectratio>stretch</aspectratio>')
        out.append(pad + '                <texture colordiffuse="%s">%s</texture>'
                   % (s['colour'], escape(media_base + s['image'])))
        if s.get('cond'):
            out.append(pad + '                <visible>%s</visible>' % escape(s['cond']))
        anim_lines(s['anims'], pad + '                ')
        out.append(pad + '            </control>')
    if cur is not None:
        out.append('            </control>')
    out += ['        </control>', '    </include>', '</includes>', '']
    return '\n'.join(out)


# ----------------------------------------------------------------------
class SkinPatcher(object):
    def __init__(self, skin_id):
        self.skin_id = skin_id
        self.cfg = SUPPORTED.get(skin_id)
        self.path = None
        self.version = ''
        self.res_dir = None
        if self.cfg:
            try:
                a = xbmcaddon.Addon(skin_id)
                self.path = a.getAddonInfo('path')
                self.version = a.getAddonInfo('version')
            except Exception:
                self.path = None

    # -- discovery --------------------------------------------------------
    def _res_dir(self):
        """Folder of the skin's 1920x1080 layout, or None."""
        try:
            text = _read(os.path.join(self.path, 'addon.xml'))
        except Exception:
            return None
        for m in re.finditer(r'<res\b[^>]*>', text):
            tag = m.group(0)
            if 'width="1920"' in tag and 'height="1080"' in tag:
                f = re.search(r'folder="([^"]+)"', tag)
                if f:
                    return f.group(1)
        return None

    def supported(self):
        if not (self.cfg and self.path and os.path.isdir(self.path)):
            return False
        self.res_dir = self._res_dir()
        if not self.res_dir:
            return False
        try:
            host = _read(os.path.join(self.path, self.res_dir, self.cfg['host_file']))
        except Exception:
            return False
        return ('<include name="%s">' % self.cfg['host_include']) in host

    # -- patching ---------------------------------------------------------
    def _patch_includes(self, data):
        nl = _nl(data)
        block = '    %s<include file="%s"/>%s%s' % (MARK_B, INCLUDE_FILE, MARK_E, nl)
        m = re.search(r'^[^\n]*%s[^\n]*\n' % re.escape(self.cfg['host_file']), data, re.M)
        if m:
            return data[:m.end()] + block + data[m.end():]
        i = data.rfind('</includes>')
        if i < 0:
            raise ValueError('no </includes> in %s' % self.cfg['includes'])
        return data[:i] + block + data[i:]

    def _patch_host(self, data):
        nl = _nl(data)
        start = data.index('<include name="%s">' % self.cfg['host_include'])
        nxt = data.find('<include name="', start + 10)
        end = data.rfind('</include>', start, nxt if nxt > 0 else len(data))
        if end < 0:
            raise ValueError('cannot find the end of %s' % self.cfg['host_include'])
        line = data.rfind('\n', 0, end) + 1
        block = '        %s%s        <include>%s</include>%s        %s%s' % (
            MARK_B, nl, INCLUDE_NAME, nl, MARK_E, nl)
        return data[:line] + block + data[line:]

    def apply(self, include_text):
        """Write the include and hook it into the skin. Returns
        (ok, changed, message). changed=True means the skin must be reloaded."""
        if not self.supported():
            return False, False, 'skin not supported'
        d = os.path.join(self.path, self.res_dir)
        changed = False
        try:
            inc = os.path.join(d, INCLUDE_FILE)
            old = _read(inc) if os.path.exists(inc) else None
            if old != include_text:
                _write(inc, include_text)
                changed = True
            for fname, patch in ((self.cfg['includes'], self._patch_includes),
                                 (self.cfg['host_file'], self._patch_host)):
                f = os.path.join(d, fname)
                data = _read(f)
                if MARK_B in data:
                    continue
                bak = f + BAK
                if not os.path.exists(bak):
                    _write(bak, data)
                _write(f, patch(data))
                changed = True
        except Exception as e:
            log('apply failed: %r' % e)
            try:
                self.remove()
            except Exception:
                pass
            return False, False, str(e)
        return True, changed, ''

    def remove(self):
        """Take the patch out again. Returns (ok, changed)."""
        if not (self.path and self.cfg):
            return True, False
        res = self.res_dir or self._res_dir()
        if not res:
            return True, False
        d = os.path.join(self.path, res)
        changed = False
        for fname in (self.cfg['includes'], self.cfg['host_file']):
            f = os.path.join(d, fname)
            try:
                data = _read(f)
            except Exception:
                continue
            if MARK_B in data:
                _write(f, _STRIP.sub('', data))
                changed = True
            if os.path.exists(f + BAK):
                os.remove(f + BAK)
        inc = os.path.join(d, INCLUDE_FILE)
        if os.path.exists(inc):
            os.remove(inc)
            changed = True
        return True, changed


def remove_everywhere():
    """Unpatch every supported skin that is installed. Returns True if any
    skin file changed (so the current skin should be reloaded)."""
    any_changed = False
    for skin_id in SUPPORTED:
        p = SkinPatcher(skin_id)
        if p.path:
            try:
                ok, ch = p.remove()
                any_changed = any_changed or ch
            except Exception as e:
                log('remove failed for %s: %r' % (skin_id, e))
    return any_changed
